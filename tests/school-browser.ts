async function cleanup() {
  if (browser) await browser.close();
  if (!ids.users.length && !ids.years.length) return;
  const enrollments = await prisma.studentEnrollment.findMany({ where: { academicYearId: { in: ids.years } }, select: { studentId: true } });
  const studentIds = [...new Set(enrollments.map(e => e.studentId))];
  const sequenceIds = (await prisma.student.findMany({ where: { id: { in: studentIds } }, select: { sequenceId: true } })).map(s => s.sequenceId);
  const exams = await prisma.exam.findMany({ where: { cohortId: { in: ids.cohorts } }, select: { id: true } });
  const examIds = exams.map(e => e.id);
  await prisma.$transaction(async tx => {
    await tx.examMark.deleteMany({ where: { examId: { in: examIds } } });
    await tx.examCandidate.deleteMany({ where: { examId: { in: examIds } } });
    await tx.examSubject.deleteMany({ where: { examId: { in: examIds } } });
    await tx.exam.deleteMany({ where: { id: { in: examIds } } });
    await tx.cohortSubject.deleteMany({ where: { cohortId: { in: ids.cohorts } } });
    if (ids.department) await tx.subject.deleteMany({ where: { departmentId: ids.department } });
    await tx.studentEnrollment.deleteMany({ where: { academicYearId: { in: ids.years } } });
    await tx.student.deleteMany({ where: { id: { in: studentIds } } });
    await tx.studentNumberSequence.deleteMany({ where: { id: { in: sequenceIds } } });
    await tx.staffAssignment.deleteMany({ where: { userId: { in: ids.users } } });
    await tx.academicCohort.deleteMany({ where: { id: { in: ids.cohorts } } });
    await tx.academicYear.deleteMany({ where: { id: { in: ids.years } } });
    if (ids.department) await tx.department.delete({ where: { id: ids.department } });
    await tx.auditLog.deleteMany({ where: { actorId: { in: ids.users } } });
    await tx.user.deleteMany({ where: { id: { in: ids.users } } });
  }, { timeout: 20000 });
  console.log("Removed only this run's temporary module test records.");
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { try { await cleanup(); } finally { await prisma.$disconnect(); } });
